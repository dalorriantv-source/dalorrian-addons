-- word -> group (first one wins; built once)
E.WORD_GROUP = {}
for group, words in pairs(E.LEXICON) do
  for w in words:gmatch("%S+") do
    if not E.WORD_GROUP[w] then E.WORD_GROUP[w] = group end
  end
end
